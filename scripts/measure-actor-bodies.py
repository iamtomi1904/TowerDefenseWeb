"""Measure body registration only. Original PNG pixels are never modified.

Head landmarks are art measurements, excluding raised weapons, ponytails,
helmet crests and halos. One anatomical scale is used through the entire action;
crouching/death poses must NOT be stretched to their standing silhouette height.
"""
from pathlib import Path
from PIL import Image
import json
ROOT=Path(__file__).resolve().parents[1]
# Standing skull/hair-to-sole spans in the 512px passive cells, measured on art.
PASSIVE_SPAN={
'darkelf':398,'guardian':333,'assassin':360,'paladin':204,
'paladin-mounted':256,'windblade':360,'duelist-critical':388,'duelist-dual':382,
'ranger':410,'tidecaller':402,'berserker':368,'ravager':358,'vanguard':320,
'guardian-max':344,'assassin-max':344,'paladin-max':206,'paladin-mounted-max':304,
'ranger-max':400,'tidecaller-max':400,'berserker-max':368,'ravager-max':358,'vanguard-max':334}
# Head top in the neutral reference cell, as a fraction of cell height.
HEAD_TOP={'dark-elf':.11,'goblin-assassin':.16,'knight-1':.15,'samurai-archer':.075,
'fire-wizard':.11,'lightning-mage':.14,'wanderer-magican':.10,'warrior-1':.13,
'warrior-3':.105,'samurai':.17,'warrior-2':.13,
'holy-foot':.28,'holy-mounted':.38,'dark-foot':.16,'dark-mounted':.32}

def measure(path,cols,rows,span=None,top=None):
    im=Image.open(path).convert('RGBA');cw=im.width/cols;ch=im.height/rows
    anchors=[]
    for n in range(cols*rows):
        x0=round(n%cols*cw);y0=round(n//cols*ch)
        cell=im.crop((x0,y0,round((n%cols+1)*cw),round((n//cols+1)*ch)))
        alpha=cell.getchannel('A');w,h=cell.size
        # Require a solid row: isolated aura sparks or spear tips are not feet.
        solid=[sum(a>180 for a in alpha.crop((0,y,w,y+1)).getdata()) for y in range(h)]
        floor=max((y+1 for y in range(h//2,h) if solid[y]>=max(3,w*.055)),default=h*.96)
        anchors.append(round(floor/h,6))
    body=span/512 if span else anchors[0]-top
    assert .2<body<1,(path,body)
    return {'columns':cols,'rows':rows,'bodyRatio':round(body,6),'originX':.5,'originsY':anchors}

out={}
for id,span in PASSIVE_SPAN.items():out['passive-action:'+id]=measure(ROOT/'public/assets/passive-actions-v1'/f'{id}.png',3,2,span=span)
for id in ['dark-elf','goblin-assassin','knight-1','samurai-archer','fire-wizard','lightning-mage','wanderer-magican','warrior-1','warrior-3','samurai']:
    name='samurai-archer-charge-v3' if id=='samurai-archer' else id
    out['refresh:'+id]=measure(ROOT/'public/assets/heroes-v2'/f'{name}.png',6,6,top=HEAD_TOP[id])
for id in ['holy-foot','holy-mounted','dark-foot','dark-mounted']:
    out['knight-v2:'+id]=measure(ROOT/'public/assets/knights-v2'/f'{id}.png',6,6,top=HEAD_TOP[id])
for id in ['knight-1','wanderer-magican','warrior-1','warrior-2','warrior-3','goblin-assassin','samurai-archer','fire-wizard','lightning-mage','holy-foot','holy-mounted','dark-foot','dark-mounted']:
    name='samurai-archer-charge-v3' if id=='samurai-archer' else id
    out['ascended:'+id]=measure(ROOT/'public/assets/ascended'/f'{name}.png',6,6,top=HEAD_TOP[id])
out['ravager-redesign']=measure(ROOT/'public/assets/ravager/hero-v2.png',6,6,top=HEAD_TOP['warrior-2'])
out['katana-forms']=measure(ROOT/'public/assets/blademaster/katana-forms.png',6,6,top=.14)
out['guardian-actions']=measure(ROOT/'public/assets/guardian/actions-v3.png',6,2,top=.25)
# Keep each troop's existing world size; only register the per-frame ground anchor.
old=(ROOT/'public/troop-layout.js').read_text(encoding='utf-8-sig').split('export const TROOP_LAYOUT=')[1].strip().rstrip(';')
troops=json.loads(old)
for id,l in troops.items():
    m=measure(ROOT/'public/assets/troops-v2'/f'{id}.png',6,6,top=.1)
    m['bodyRatio']=l['bodyRatio'];m['heightMultiplier']=l['originalRatio'];m['originX']=l['originX']
    out['troop-v2:'+id]=m
(ROOT/'public/actor-body-layout.js').write_text('// Anatomical reference scale and solid ground anchors; generated by scripts/measure-actor-bodies.py.\nexport const ACTOR_BODY_LAYOUT='+json.dumps(out,separators=(',',':'))+';\n',encoding='utf-8')
# Keep the standalone passive renderer aligned with the shared registration path.
p=ROOT/'public/passive-action-layout.js';data=json.loads(p.read_text(encoding='utf-8-sig').split('=')[1].strip().rstrip(';'))
for id,l in data.items():
    m=out['passive-action:'+id];l.update(bodyRatio=m['bodyRatio'],originX=m['originX'],originsY=m['originsY'])
p.write_text('export const PASSIVE_ACTION_LAYOUT='+json.dumps(data,indent=2)+';\n',encoding='utf-8')
print('Registered',len(out),'body atlases without altering PNGs')
